#!/usr/bin/env node
// Regenerates docs/MAINTAINER-DECISIONS.md — the list of issues an autonomous agent must not
// complete alone. Run after any change to issues/*.json.
import { readFileSync, readdirSync, writeFileSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const ISSUES_DIR = join(ROOT, 'issues');
const skip = ['labels.json', 'milestones.json', '.published.json'];
const all = readdirSync(ISSUES_DIR)
  .filter(f => f.endsWith('.json') && !skip.includes(f))
  .flatMap(f => JSON.parse(readFileSync(join(ISSUES_DIR, f), 'utf8')));
const published = existsSync(join(ISSUES_DIR, '.published.json'))
  ? JSON.parse(readFileSync(join(ISSUES_DIR, '.published.json'), 'utf8')) : {};
const order = JSON.parse(readFileSync(join(ISSUES_DIR, 'milestones.json'), 'utf8')).map(m => m.title);

const pick = label => all
  .filter(i => (i.labels_extra || []).includes(label))
  .sort((a, b) => order.indexOf(a.milestone) - order.indexOf(b.milestone) || a.key.localeCompare(b.key));

const ref = i => published[i.key] ? `#${published[i.key].number}` : '`' + i.key + '`';
const row = i => `| ${ref(i)} | ${i.title.replace(/\|/g, '\\|')} | ${i.milestone.split(' ')[0]} | ${i.areas[0]} | ${i.priority} |`;
const table = list => `| Issue | Title | Milestone | Area | Priority |\n|---|---|---|---|---|\n${list.map(row).join('\n')}`;

const decisions = pick('needs-decision');
const creds = pick('needs-credentials');

const md = `# Maintainer decisions

> Generated by \`scripts/maintainer-decisions.mjs\` from \`issues/*.json\`. Do not edit by hand.

Every other issue in the tracker is \`agent-ready\` — fully specified, safe to hand to a coding
agent. The ${decisions.length + creds.length} issues below are the exceptions: they need something only you can supply.

## Needs a decision from you (${decisions.length})

A product, architecture, legal or vendor choice an agent must not make unilaterally. Each issue
lays out the options and trade-offs in its **Context** and **Technical notes**.

${table(decisions)}

## Needs credentials or accounts from you (${creds.length})

Blocked on secrets only you can provide: OAuth client IDs and secrets, Apple Developer and Play
Console access, signing certificates and notarization keys, store listings, a security contact
mailbox and PGP key.

${table(creds)}

## How to unblock one

1. Open the issue and read **Context** and **Technical notes** — the options are laid out there.
2. Record your decision as a comment, or add the secret under
   *Settings → Secrets and variables → Actions* (never commit it).
3. Swap the \`needs-decision\` / \`needs-credentials\` label for \`agent-ready\`.
4. The issue is then safe to hand to any coding agent.

Unresolved entries block their milestone's exit criteria — see \`docs/roadmap.md\`.
`;

writeFileSync(join(ROOT, 'docs', 'MAINTAINER-DECISIONS.md'), md);
console.log(`needs-decision: ${decisions.length}, needs-credentials: ${creds.length}`);
